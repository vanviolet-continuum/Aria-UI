import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import { format, resolveConfig } from 'prettier'

const root = fileURLToPath(new URL('../../', import.meta.url))
const catalogDir = path.join(root, 'preview/src/catalog')
await mkdir(catalogDir, { recursive: true })
const counts = {}
const formatConfig = await resolveConfig(catalogDir)
for (const [kind, source, suffix] of [
  ['icons', 'templates/icons', '.icon'],
  ['illustrations', 'templates/ui/illustrations', '.illustration'],
]) {
  const items = []
  for (const directory of await readdir(path.join(root, source), { withFileTypes: true })) {
    if (!directory.isDirectory()) continue
    let index
    try {
      index = await readFile(path.join(root, source, directory.name, 'index.ts'), 'utf8')
    } catch (error) {
      if (error.code === 'ENOENT') continue
      throw error
    }
    for (const match of index.matchAll(/export \{ (\w+) \} from '\.\/(.+)'/g)) {
      if (
        !match[2].endsWith(suffix) &&
        !(kind === 'illustrations' && match[2].endsWith('.decoration'))
      )
        continue
      items.push({
        name: match[1],
        category: directory.name,
        path: `@${source}/${directory.name}/${match[2]}`,
      })
    }
  }
  items.sort((a, b) => a.name.localeCompare(b.name))
  counts[kind] = items.length
  const imports = items.map((item) => `import { ${item.name} } from '${item.path}'`).join('\n')
  const records = items
    .map(
      ({ name, category, path }) =>
        `  { name: '${name}', category: '${category}', path: '${path}', Component: ${name} },`,
    )
    .join('\n')
  await writeFile(
    path.join(catalogDir, `${kind}.ts`),
    await format(
      `// Generated by npm run demo:catalog from public leaf exports.\n// The complete asset registry belongs only to this demo.\nimport type { GalleryAsset } from '../components/asset.gallery'\n${imports}\n\nexport const ${kind}: GalleryAsset[] = [\n${records}\n]\n`,
      { ...formatConfig, parser: 'typescript' },
    ),
  )
}
await writeFile(path.join(catalogDir, 'counts.json'), JSON.stringify(counts, null, 2) + '\n')
console.log(`Catalog: ${counts.icons} icons, ${counts.illustrations} illustrations`)

// The documentation sidebar follows the actual public component folders.
const components = []
for (const entry of await readdir(path.join(root, 'templates/ui'), { withFileTypes: true })) {
  if (!entry.isDirectory()) continue
  try {
    const publicApi = await readFile(
      path.join(root, 'templates/ui', entry.name, 'index.ts'),
      'utf8',
    )
    components.push({
      id: entry.name,
      label: entry.name
        .split('.')
        .map((word) => word[0].toUpperCase() + word.slice(1))
        .join(' '),
      publicApi,
    })
  } catch (error) {
    if (error.code !== 'ENOENT') throw error
  }
}
components.sort((a, b) => a.id.localeCompare(b.id))
await writeFile(
  path.join(catalogDir, 'components.ts'),
  await format(
    '// Generated from the public UI folders by preview/scripts/update.catalog.mjs.\nexport const components = ' +
      JSON.stringify(components, null, 2) +
      ' as const\n',
    { ...formatConfig, parser: 'typescript' },
  ),
)
